"""Emit the explicit SM maintenance contract adapter (no reflection dispatch)."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
INTERFACES = ['IBusinessApplication', 'IParcelApplication', 'IWorkstationAdministration',
              'ICameraDiagnostics', 'ICameraAcquisitionDiagnostics', 'ICameraInspection',
              'ICameraReadRounds', 'IParcelConfigurationDraftApplication', 'IRuntimeDiagnosticsControl',
              'IStationOperations', 'IDiagnosticPackageApplication', 'IStationDiagnostics',
              'ISmRemoteRecovery', 'IManagementWorkspace', 'IParcelHistoryApplication',
              'IParcelHistorySessionApplication', 'IParcelHistoryBatchApplication', 'ICompleteBackupSetMaintenance']
REFUSED = {'LoginAsync', 'LogoutAsync', 'AuthorizeMaintenanceAsync', 'ManageCapabilityAsync',
           'InstallCapabilityAsync', 'ReconnectAsync', 'QueryAsync', 'EmitReference',
           'EmitReferenceAt', 'EmitReferenceWeight', 'EnterManagementModeAsync'}

def split_parameters(text):
    result, begin, depth = [], 0, 0
    for i, c in enumerate(text):
        if c in '<([': depth += 1
        elif c in '>)]': depth -= 1
        elif c == ',' and depth == 0:
            result.append(text[begin:i].strip()); begin = i + 1
    if text[begin:].strip(): result.append(text[begin:].strip())
    return [p.split(' = ')[0] for p in result]

sources = '\n'.join(p.read_text(encoding='utf-8-sig') for p in (ROOT/'src/Ipc.Application.Contracts').glob('*.cs'))
sources += '\n' + (ROOT/'src/Ipc.Platform/BusinessAssembly.cs').read_text(encoding='utf-8-sig')
proxy = ['// Generated by scripts/generate-operations-adapter.py; edit the contract/source, then regenerate.', '#nullable enable',
         'using Ipc.Application.Contracts;', 'using Ipc.Platform;', 'namespace Ipc.Operations;',
         'public sealed class OperationsRemoteApplication(OperationsControlClient channel, ParcelConfigurationLocations locations) : ' + ', '.join(INTERFACES + ['IParcelConfigurationLocationApplication', 'ISoftwareLogSelectionLifetime']), '{',
         '    public ParcelConfigurationLocations ConfigurationLocations => locations;',
         '    public void ReleaseLogSelection(string selection) => channel.ReleaseLogSelection(selection);']
dispatch = ['// Generated by scripts/generate-operations-adapter.py; explicit protocol whitelist.', '#nullable enable',
            'using System.Text.Json;', 'using Ipc.Application.Contracts;', 'using Ipc.Platform;',
            'namespace Ipc.Operations;', 'internal static class OperationsDispatch', '{',
            '    static T Arg<T>(JsonElement[] args, int index) => args[index].Deserialize<T>()!;',
            '    internal static async Task<object?> Invoke(IParcelApplication application, string operation, JsonElement[] args, CancellationToken token, ICompleteBackupSetMaintenance? backupSets = null, IProgress<MaintenanceProgress>? progress = null)',
            '    {', '        switch (operation)', '        {']
for interface in INTERFACES:
    found = re.search(r'public interface '+interface+r'\b[^\{]*\{', sources)
    if not found: raise ValueError(interface)
    begin, end, depth = found.end(), found.end(), 1
    while depth:
        if sources[end] == '{': depth += 1
        elif sources[end] == '}': depth -= 1
        end += 1
    body = sources[begin:end-1]
    for m in re.finditer(r'^\s*(Task(?:<[^\n]+?>)?|bool)\s+(\w+)\(([^\n]*?)\)', body, re.M):
        returns, name, raw = m.groups()
        parameters = split_parameters(raw)
        args, call, token, index, progress = [], [], 'CancellationToken.None', 0, None
        for p in parameters:
            typ, var = p.rsplit(' ', 1)
            if typ == 'CancellationToken':
                token = var; call.append('token')
            elif typ.startswith('IProgress<MaintenanceProgress>'):
                progress = var; call.append('progress')
            else:
                args.append(var); call.append(f'Arg<{typ}>(args, {index})'); index += 1
        key = f'{interface}.{name}/{index}' + ('p' if progress else '')
        signature = f'    {returns} {interface}.{name}({", ".join(parameters)})'
        if name in REFUSED or name == 'ResetManagementPasswordAsync' and index == 2:
            proxy.append(signature + ' => throw new NotSupportedException("此能力不属于运维控制契约。");')
            continue
        wireargs = '[' + ', '.join(args) + ']'
        generic = returns[5:-1] if returns.startswith('Task<') else None
        if generic:
            method = 'CallMaintenanceAsync' if name in {'ExportBackupSetAsync', 'DeleteBackupSetAsync', 'BackupAsync'} else 'CallAsync'
            proxy.append(signature + f' => channel.{method}<{generic}>("{key}", {wireargs}, {token}' + (', '+progress if progress else '') + ');')
        else:
            proxy.append(signature + f' => channel.CallAsync("{key}", {wireargs}, {token});')
        dispatch += [f'            case "{key}":', f'                if (args.Length != {index}) throw new InvalidDataException("命令参数数量无效。");']
        target = '(backupSets ?? throw new NotSupportedException("当前宿主未提供完整备份保管服务。"))' if interface == 'ICompleteBackupSetMaintenance' else f'(({interface})application)'
        expr = f'await {target}.{name}({", ".join(call)}).ConfigureAwait(false)'
        dispatch.append('                return '+expr+';' if generic else '                '+expr+'; return null;')
proxy.append('}')
dispatch += ['            default: throw new UnauthorizedAccessException("未授予此运维命令。");', '        }', '    }', '}']
(ROOT/'src/Ipc.Operations/OperationsRemoteApplication.g.cs').write_text('\n'.join(proxy)+'\n', encoding='utf-8')
(ROOT/'src/Ipc.Operations/OperationsDispatch.g.cs').write_text('\n'.join(dispatch)+'\n', encoding='utf-8')
